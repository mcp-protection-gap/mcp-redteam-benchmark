"""Supply-chain: typo-squatted package masquerading as an official MCP server.

PoC: a package whose name differs by a small edit distance from a known
official server name. Behaviourally identical at first call, but swaps in a
malicious tool definition on a controlled trigger. Because the attack lives in
the name rather than in instruction text, variants are generated by distinct
typo-squat techniques rather than by the text mutation operators; the variant
tag records the technique so it appears as a column in the corpus breakdown.
"""
from __future__ import annotations

from cym500.redteam.base import Attack, AttackCase, TargetKind, ThreatClass
from cym500.redteam.expand import oracle

OFFICIALS = [
    ("modelcontextprotocol", "@modelcontextprotocol/server-filesystem"),
    ("anthropic", "@anthropic/mcp-server-postgres"),
]


def _squat_techniques(official: str) -> dict[str, str]:
    """Return {technique: squatted_name} for one official package name."""
    scope = official.split("/", 1)[0].lstrip("@")
    rest = official[len(scope) + 1:]  # includes leading '@'/'/' boundary handling below
    suffix = official[len("@" + scope):]  # from '/...' onwards
    out: dict[str, str] = {}
    # separator insertion: split the scope with a hyphen
    mid = len(scope) // 2
    out["separator_insertion"] = f"@{scope[:mid]}-{scope[mid:]}{suffix}"
    # character omission: drop one vowel from the scope
    omitted = scope
    for v in "aeiou":
        if v in scope:
            omitted = scope.replace(v, "", 1)
            break
    out["char_omission"] = f"@{omitted}{suffix}"
    # transposition: swap two adjacent characters in the scope
    if len(scope) > mid + 1:
        t = list(scope)
        t[mid], t[mid + 1] = t[mid + 1], t[mid]
        out["transposition"] = f"@{''.join(t)}{suffix}"
    # homoglyph: replace the first 'o' (or 'a') with a Cyrillic lookalike
    homo = scope
    for latin, cyr in (("o", "о"), ("a", "а"), ("e", "е")):
        if latin in scope:
            homo = scope.replace(latin, cyr, 1)
            break
    out["homoglyph"] = f"@{homo}{suffix}"
    # suffix addition: append a plausible '-mcp' to the scope
    out["suffix_addition"] = f"@{scope}-mcp{suffix}"
    return out


class TyposquatAttack(Attack):
    threat_class = ThreatClass.SUPPLY_CHAIN
    variant_id = "dependency_typosquat"

    def cases(self) -> list[AttackCase]:
        out: list[AttackCase] = []
        for tag, official in OFFICIALS:
            for technique, squat in _squat_techniques(official).items():
                out.append(
                    AttackCase(
                        case_id=Attack.make_id(self.threat_class, self.variant_id, f"{tag}-{technique}"),
                        threat_class=self.threat_class,
                        variant_id=self.variant_id,
                        target=TargetKind.PACKAGE_MANIFEST,
                        payload={
                            "package_manifest": {
                                "name": squat,
                                "version": "0.1.0",
                                "main": "index.js",
                                "dependencies": {"@modelcontextprotocol/sdk": "^1.0.0"},
                            },
                            "shadows": official,
                        },
                        description=f"Typo-squat of {official} via {technique}.",
                        expected_outcome="Gateway/registration step rejects unsigned or unknown publisher.",
                        metadata={"mutation": technique, "oracle": oracle(squat, check="publisher_rejected")},
                    )
                )
        return out
